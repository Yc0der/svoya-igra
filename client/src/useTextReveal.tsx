import { useMemo, type ReactNode } from 'react';

// Буквы проявляются за это время (design.md,
// 2026-08-19-gradual-text-reveal-design.md, «Буква проявляется, а не
// возникает»). Константа, не настраиваемый параметр — 200мс подобраны
// сравнением на живом примере 2026-08-21, отдельной крутилки в админке не
// заводится (в отличие от скорости чтения, см. Admin.tsx).
export const TEXT_REVEAL_FADE_MS = 200;

// Табло показывает вопрос по буквам, пока идёт постепенный показ — темп
// синхронизирован с серверным таймером (deadline/revealMs из
// GameStateView), а не своим независимым отсчётом: иначе табло и правило
// «кнопка появляется по концу показа» (движок) разъедутся. deadline/revealMs
// — null вне фазы question-reveal, тогда возвращается text целиком без
// разметки.
//
// По буквам, не по словам — живая проверка 2026-08-19 показала, что показ
// целыми словами выглядит неестественно (слово либо есть целиком, либо его
// нет, без ощущения печати/чтения). Длительность (revealMs) при этом
// по-прежнему считается Комнатой по числу СЛОВ (слова/сек — та единица, в
// которой разумно думать о темпе чтения) — на клиенте это никак не участвует,
// здесь мы просто делим уже готовый revealMs на число символов.
//
// Живая проверка 2026-08-21 показала: одной лишь высокой частоты пересчёта
// (requestAnimationFrame, предел кадровой частоты) недостаточно — каждая
// буква всё равно прыгала из полной прозрачности в полную непрозрачность
// мгновенно, а таких прыжков при темпе 2,5 слова/сек набегает около
// семнадцати в секунду, и глаз читает их как дрожание. Разгонялась не та
// величина: не частота пересчёта, а сам момент появления буквы должен быть
// растянут во времени. Поэтому цикл по кадрам убран целиком: текст один раз
// раскладывается на буквы, каждой прописывается своя задержка старта
// CSS-анимации проявления, дальше плавностью занимается браузер, а не наш
// код на каждом кадре.
export function useTextReveal(
  deadline: number | null,
  revealMs: number | null,
  text: string,
): ReactNode {
  return useMemo(() => {
    if (deadline === null || revealMs === null || revealMs <= 0) return text;

    // Реальный момент начала показа по серверному таймеру — не момент
    // монтирования компонента. Табло может подключиться или перезагрузиться,
    // когда показ уже идёт (переоткрытие вопроса, обновление страницы),
    // поэтому задержка каждой буквы считается от него: для уже показанных
    // букв она выходит отрицательной, а отрицательный animation-delay CSS
    // трактует как «анимация началась в прошлом» и сразу показывает
    // соответствующий (уже завершённый) кадр — то есть букву целиком
    // непрозрачной, без ожидания.
    const revealStartedAt = deadline - revealMs;
    const now = Date.now();

    // Считаем позицию каждого символа в исходном тексте (index), включая
    // пробелы — тот же счётчик, что раньше использовался для text.length в
    // формуле среза. Разбиваем на слова и пробельные промежутки между ними
    // регуляркой с сохранением разделителя: чередование «слово, пробел,
    // слово, …».
    const tokens = text.split(/(\s+)/).filter((token) => token !== '');
    let index = 0;

    const nodes: ReactNode[] = tokens.map((token, tokenIndex) => {
      if (/^\s+$/.test(token)) {
        // Пробел — обычный текстовый узел: именно на нём браузеру разрешено
        // переносить строку.
        index += token.length;
        return token;
      }

      const letters = [...token].map((char, i) => {
        const charIndex = index + i;
        // Момент, когда эта буква должна начать проявляться — линейно по её
        // позиции в тексте, та же пропорция, что раньше давал
        // text.slice(0, count) на каждом кадре.
        const letterStartsAt =
          revealStartedAt + (charIndex * revealMs) / text.length;
        return (
          <span
            key={i}
            className="text-reveal-letter"
            style={{
              animationDelay: `${letterStartsAt - now}ms`,
              animationDuration: `${TEXT_REVEAL_FADE_MS}ms`,
            }}
          >
            {char}
          </span>
        );
      });
      index += token.length;

      // Слово — неразрывный блок: без этого браузер вправе разорвать строку
      // между соседними инлайн-элементами (буквами), и перенос может
      // случиться посреди слова.
      return (
        <span key={tokenIndex} className="text-reveal-word">
          {letters}
        </span>
      );
    });

    return nodes;
  }, [deadline, revealMs, text]);
}
