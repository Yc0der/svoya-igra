import { constants } from 'node:fs';
import { copyFile } from 'node:fs/promises';

/**
 * Создаёт рабочий файл из примера, если его ещё нет.
 *
 * Три файла проекта — анкеты игроков, профиль генератора и текущий пакет —
 * содержат данные конкретной компании, а не проекта, и потому лежат в
 * .gitignore. В репозитории от каждого остаётся только `*.example.*`, и на
 * свежем клоне рабочего файла нет вовсе: без этого шага сервер не нашёл бы
 * пакет вопросов, а первая же вставка анкеты в /admin упала бы с ENOENT —
 * savePlayerCard читает файл перед записью.
 *
 * Ничего не делает, если файл уже есть (EEXIST): затереть чужие анкеты
 * примером хуже, чем не создать файл. Отсутствие самого примера (ENOENT)
 * тоже не повод не стартовать — сервер поднимется, список анкет будет пуст.
 */
export async function ensureFileFromExample(
  path: string,
  examplePath: string,
): Promise<void> {
  try {
    await copyFile(examplePath, path, constants.COPYFILE_EXCL);
  } catch {
    // Оба случая штатные — см. комментарий выше.
  }
}
