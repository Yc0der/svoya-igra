/**
 * Общий предел на весь запуск вместо предела на каждую операцию.
 *
 * Покомандный таймаут ограничивает одну операцию, а не работу целиком: чтение stdin
 * плюс четыре git-вызова по 2 с складываются в 10 с — ровно во внешний timeout хука
 * из `settings.json`, то есть собственный предел не даёт никакого запаса. Общий бюджет
 * убирает сложение: сколько бы операций ни понадобилось, суммарно они не выйдут за него.
 *
 * `now` вынесен в параметр только ради тестов — в бою это `Date.now`.
 */
export function createDeadline(budgetMs, now = Date.now) {
  const end = now() + budgetMs;
  return {
    /**
     * Сколько миллисекунд осталось. Ноль — бюджет исчерпан, работу надо бросать:
     * передавать его дальше как таймаут нельзя, для `execFileSync` `timeout: 0`
     * означает «без предела».
     */
    left: () => Math.max(0, end - now()),
  };
}
